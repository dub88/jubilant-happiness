/**
 * A copyright notice and its year or year range: "© 2019–2024 Name", "© Name 2024",
 * "Copyright 2024", "(c) 2024". The bare word "copyright" must be followed
 * directly by the year, so prose about copyright is not read as a notice.
 */
const COPYRIGHT =
  /(?:©[^\n]{0,60}?|\bcopyright\s*(?:©|\(c\))?\s*|\(c\)\s*)\b((?:19|20)\d{2})\b(?:\s*[-–—]\s*((?:19|20)\d{2})\b)?/gi;

export const slopRules: Rule[] = [
  {
    id: 'default-metadata',
    severity: 'error',
    summary: "The title or description is a framework's or site builder's default.",
    check: (site) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        const title = page.titles[0];
        if (title && DEFAULT_TITLES.has(title.toLowerCase())) {
          problems.push({
            path: page.key,
            message: `The title is a starter default: "${title}".`,
            fix: 'Write a title for this page.',
            detail: 'title',
            needle: title,
          });
        }
        const description = page.description;
        if (description && DEFAULT_DESCRIPTIONS.has(description.toLowerCase().replace(/\.$/, ''))) {
          problems.push({
            path: page.key,
            message: `The meta description is a starter default: "${description}".`,
            fix: 'Write a description for this page.',
            detail: 'description',
            needle: description,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'starter-content',
    severity: 'error',
    summary: "The page still shows a framework's starter content.",
    check: (site) =>
      textMatches(site, STARTER_CONTENT, (framework, quoted) => ({
        message: `The page still shows ${framework} starter content: ${quoted}`,
        fix: 'Replace the starter page with real content.',
      })),
  },
  {
    id: 'default-favicon',
    severity: 'error',
    summary: "The favicon is a framework's default icon.",
    check: (site) =>
      site.icons.flatMap((icon) => {
        const framework = icon.sha256 && DEFAULT_FAVICONS.get(icon.sha256);
        return framework
          ? [{ path: icon.url, message: `The favicon is the default ${framework} icon.`, fix: "Replace it with the business's own icon." }]
          : [];
      }),
  },
  {
    id: 'favicon-missing',
    severity: 'warning',
    summary: 'No favicon loads.',
    check: (site) => {
      if (site.icons.length === 0 || site.icons.some((icon) => icon.status === 200)) return [];
      return site.icons.map((icon) => ({
        path: icon.url,
        message: `The favicon ${icon.url} ${icon.status === 0 ? 'does not respond' : `returns ${icon.status}`}.`,
        fix: 'Add a favicon and link it with <link rel="icon">.',
      }));
    },
  },
  {
    id: 'placeholder-text',
    severity: 'error',
    summary: 'Placeholder text is still on the page (lorem ipsum, "[Your Name]", "text goes here").',
    check: (site) =>
      textMatches(
        site,
        PLACEHOLDER_TEXT,
        (_label, quoted) => ({ message: `Placeholder text is still on the page: ${quoted}`, fix: 'Replace it with real copy.' }),
        (page) => `${page.titles[0] ?? ''}\n${page.description ?? ''}`,
      ),
  },
  {
    id: 'unrendered-template',
    severity: 'error',
    summary: 'A template tag or a stringified value is shown to visitors ("{{ name }}", "[object Object]", "undefined" in a title).',
    check: (site) => {
      const metadata = (page: PageData): string => `${page.titles[0] ?? ''}\n${page.description ?? ''}`;
      const problems = textMatches(
        site,
        UNRENDERED,
        (_label, quoted) => ({ message: `Unrendered template output is visible: ${quoted}`, fix: 'Fix the template so the value is filled in.' }),
        metadata,
      );
      for (const page of site.pages) {
        const fields: [string, string | undefined][] = [['title', page.titles[0]], ['meta description', page.description]];
        for (const [field, value] of fields) {
          const match = value ? MISSING_VALUE.exec(value) : null;
          if (!match) continue;
          problems.push({
            path: page.key,
            message: `The ${field} contains a missing value: "${value}"`,
            fix: 'A value was empty when the page was built; give it a fallback.',
            detail: field,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'placeholder-contact',
    severity: 'error',
    summary: 'Made-up contact details are shown (an example.com address, a 555 number, "123 Main Street").',
    check: (site) =>
      textMatches(site, PLACEHOLDER_CONTACT, (kind, quoted) => ({
        message: `A placeholder ${kind} is shown: ${quoted}`,
        fix: "Replace it with the business's real details, or remove it.",
      })),
  },
  {
    id: 'placeholder-image',
    severity: 'error',
    summary: 'An image comes from a placeholder service or a placeholder file.',
    check: (site) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        for (const src of new Set(page.images.map((image) => image.src))) {
          if (!PLACEHOLDER_IMAGE_HOSTS.test(src) && !PLACEHOLDER_IMAGE_FILE.test(src)) continue;
          problems.push({
            path: page.key,
            message: `Placeholder image: ${src.length > 90 ? `${src.slice(0, 90)}…` : src}`,
            fix: 'Replace it with a real image.',
            detail: src,
            needle: src,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'generic-alt',
    severity: 'warning',
    summary: 'An image\'s alt text is a filler word or a file name ("image", "hero.jpg").',
    check: (site) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        const seen = new Set<string>();
        for (const { src, alt } of page.images) {
          if (!alt || seen.has(src) || !(GENERIC_ALT.has(alt.toLowerCase()) || FILENAME_ALT.test(alt))) continue;
          seen.add(src);
          problems.push({
            path: page.key,
            message: `Alt text "${alt}" does not describe the image ${src.length > 70 ? `${src.slice(0, 70)}…` : src}.`,
            fix: 'Say what the image shows, or use alt="" if it is decorative.',
            detail: src,
            needle: src,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'dead-link',
    severity: 'warning',
    summary: 'A link goes nowhere (href="#", empty, or javascript:).',
    check: (site) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        for (const label of new Set(page.deadLinks)) {
          // href="#" is the usual way to write a "back to top" link.
          if (BACK_TO_TOP.test(label)) continue;
          problems.push({
            path: page.key,
            message: `The link "${label.length > 60 ? `${label.slice(0, 60)}…` : label}" goes nowhere.`,
            fix: 'Point it at a real destination, or remove it.',
            detail: label,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'placeholder-social-link',
    severity: 'warning',
    summary: "A social link points at the network's home page, not at a profile.",
    check: (site) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        for (const ref of page.refs) {
          if (ref.kind !== 'link') continue;
          const url = new URL(ref.url);
          if (!SOCIAL_HOSTS.has(url.hostname.replace(/^www\./, '')) || url.pathname.replace(/\/$/, '') !== '' || url.search) continue;
          problems.push({
            path: page.key,
            message: `A social link points at ${url.origin}, not at a profile.`,
            fix: "Link to the business's own profile, or remove the link.",
            detail: url.hostname,
            needle: ref.raw,
          });
        }
      }
      return problems;
    },
  },
  {
    id: 'stock-phrases',
    severity: 'warning',
    summary: 'The page leans on stock marketing phrases ("elevate your", "look no further").',
    check: (site, { thresholds }) => {
      const problems: Problem[] = [];
      for (const page of site.pages) {
        const found = new Set<string>();
        for (const phrase of STOCK_PHRASES) {
          const match = phrase.exec(page.text);
          if (match) found.add(match[0].toLowerCase());
        }
        if (found.size < thresholds.stockPhrases) continue;
        const listed = [...found].slice(0, 6).map((phrase) => `"${phrase}"`);
        problems.push({
          path: page.key,
          message: `The page uses ${found.size} stock phrases: ${listed.join(', ')}${found.size > 6 ? ', …' : ''}.`,
          fix: 'Say what this business actually does, in its own words.',
        });
      }
      return problems;
    },
  },
  {
    id: 'emoji-icons',
    severity: 'warning',
    summary: 'Emoji are used as icons or to decorate headings.',
    check: (site) =>
      site.pages
        .filter((page) => page.emojiIcons.length >= 3)
        .map((page) => ({
          path: page.key,
          message: `${page.emojiIcons.length} emoji are used as icons or in headings: ${[...new Set(page.emojiIcons)].slice(0, 8).join(' ')}`,
          fix: 'Use a consistent icon set, or none.',
        })),
  },
  {
    id: 'stale-copyright',
    severity: 'warning',
    summary: 'The copyright year is in the past.',
    check: (site, { now }) => {
      const thisYear = now.getUTCFullYear();
      const problems: Problem[] = [];
      for (const page of site.pages) {
        let latest: { year: number; text: string } | undefined;
        for (const match of page.text.matchAll(COPYRIGHT)) {
          const year = Math.max(Number(match[1]), Number(match[2] ?? 0));
          if (!latest || year > latest.year) latest = { year, text: match[0] };
        }
        if (!latest || latest.year >= thisYear) continue;
        problems.push({
          path: page.key,
          message: `The copyright year is ${latest.year}.`,
          fix: 'Update it, or generate the year when the page is built.',
          needle: latest.text,
        });
      }
      return problems;
    },
  },
];
